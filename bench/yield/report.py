"""Generate the current yield report from validated observations, preserving history."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--data-path", required=True, help="Library-relative result directory")
    args = parser.parse_args()
    data = json.loads((args.results / "summary.json").read_text())
    if data["cases"] != 442 or len(data["groups"]) != 102:
        raise ValueError("The current report requires the complete yield matrix")
    primary = [
        g
        for g in data["groups"]
        if g["group"] == "primary"
        and not g["trace"]
        and not g["control"]
        and g["mode"] in ("direct", "chain")
    ]
    lines = [
        (
            "// Copyright (c) 2026 WebCpp.org\n//\n// Distributed under the Boost Software License,"
            " Version 1.0. (See\n// accompanying file LICENSE_1_0.txt or copy at\n//"
            " https://www.boost.org/LICENSE_1_0.txt)\n"
        ),
        "// Generated by bench/yield/report.py. Do not edit.\n",
        "[#asio-yield-current]\n== Yield measurements of the shipped implementation\n\n",
        (
            f'This fresh local experiment began at `{data["started"]}` using `{data["browser"]}`.'
            " It measures the current shipped Asio backend with Release `-O3`, independently of"
            " the historical October experiment below. Both JavaScript and Wasm artifacts and the"
            " implementation source are fingerprinted before execution. Builds and conformance"
            " tests from this session completed before sampling; other user and OS activity is not"
            " controlled.\n\n"
        ),
        (
            "The interval is the handoff to the browser and return to {cpp}, excluding the callback"
            " batch. It includes the dispatcher return/reentry boundary. {cpp} and JavaScript"
            " monotonic clocks share the browser time origin; wall-clock bracket checks and"
            " pure-JavaScript controls test the measurement. The default remains `100` handlers per"
            " turn. This is a scheduling policy, not a time budget or a guarantee of"
            " rendering/input latency.\n\n"
        ),
        '[cols="1,1,1,1,1",options="header"]\n|===\n',
        (
            "|Variant |Handlers per turn |Median of mean gaps (us) |Median of p95 gaps (us)"
            " |Derived cost per handler (ns)\n"
        ),
    ]
    for group in sorted(primary, key=lambda g: (g["variant"], g["mode"] == "chain", g["limit"])):
        direct = group["mode"] == "direct"
        gap = group["mean_us"]["median"]
        derived = "n/a" if direct else f'{gap*1000/group["limit"]:.2f}'
        label = "direct yield" if direct else str(group["limit"])
        lines += [
            f'|{group["variant"]} |{label} |{gap:.3f} |{group["p95_us"]["median"]:.3f} |{derived}\n'
        ]
    lines += [
        "|===\n\n",
        (
            f'All {data["cases"]} cases passed validation: {data["total_operations"]:,} operations'
            f' and {data["total_samples"]:,} timestamp pairs. Seven primary repetitions and three'
            " secondary-control repetitions are retained. Percentiles in the table are medians of"
            " per-run percentiles, not a pooled tail guarantee. Dividing the measured gap by the"
            " turn limit is an amortized estimate; it does not measure the callback work"
            " itself.\n\n"
        ),
        (
            "Additional groups cover no exceptions, ordinary nonisolated pages, tracing, clocks,"
            " synchronous language crossings and arithmetic work. A zero clock tick does not prove"
            " zero cost. The complete distributions, ranges and paired controls remain in"
            " `runs.csv` and `summary.json`.\n\n"
        ),
        (
            f"`{args.data_path}` retains the generated results, build/environment metadata and raw"
            " evidence archive with its SHA-256 file. `bench/yield/README.adoc` gives the"
            " reproduction commands. This is a headless otherwise idle-page experiment, not a"
            " loaded application or remote CI run.\n\n"
        ),
    ]
    for name, title in (
        ("01-yield-latency", "Yield gap and derived amortization"),
        ("02-direct-and-phases", "Direct controls and traced phases"),
        ("03-chain-controls", "Callback chain controls"),
        ("04-tails-and-clocks", "Tails and observed clocks"),
    ):
        lines += [
            f".{title}\nimage::{{library-root}}/{args.data_path}/figures/{name}.svg"
            f"[{title},opts=inline]\n\n"
        ]
    args.output.write_text("".join(lines))


if __name__ == "__main__":
    main()
